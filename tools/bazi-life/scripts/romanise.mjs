// One pinyin syllable in Wade–Giles, Taiwanese passport style.
export function wadeGiles(py) {
  const WHOLE = { zi: "tzu", ci: "tzu", si: "szu", zhi: "chih", chi: "chih", shi: "shih", ri: "jih", yi: "yi", you: "yu", yu: "yu", yue: "yueh", yuan: "yuan", yun: "yun", yong: "yung", yan: "yen", ye: "yeh", er: "erh", e: "o", a: "a" };
  if (WHOLE[py]) return WHOLE[py];
  const m = /^(zh|ch|sh|[bpmfdtnlgkhjqxrzcsyw]?)(.*)$/.exec(py);
  let [, ini, fin] = m;
  const INI = { zh: "ch", ch: "ch", sh: "sh", r: "j", z: "ts", c: "ts", j: "ch", q: "ch", x: "hs", b: "p", d: "t", g: "k" };
  const palatal = "jqx".includes(ini) && ini;
  if (palatal) fin = fin.replace(/^u/, "ü");
  if (fin === "e") fin = "gkh".includes(ini) && ini ? "o" : "e";
  else if (fin === "uo") fin = ["g", "k", "h", "sh"].includes(ini) ? "uo" : "o";
  else if (fin === "ui") fin = ["g", "k"].includes(ini) ? "uei" : "ui";
  fin = fin.replace(/iong$/, "iung").replace(/ong$/, "ung").replace(/ian$/, "ien").replace(/ie$/, "ieh").replace(/üe$/, "üeh").replace(/ü/g, "u");
  return (INI[ini] ?? ini) + fin;
}

const parse = text => Object.fromEntries(text.trim().split(/\s+/).map(x => { const m = /^(\p{Script=Han}+)(.+)$/u.exec(x); return [m[1], m[2]]; }));
const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const py = parse(PINYIN), surnames = parse(SURNAMES);
  const chars = Object.fromEntries(Object.entries(py).map(([c, p]) => [c, wadeGiles(p)]));
  const need = new Set(ALL_NAME_PARTS.given.flatMap(g => [...g]));
  const lost = [...need].filter(c => !chars[c]);
  const noSurname = ALL_NAME_PARTS.surnames.filter(s => !surnames[s]);
  if (lost.length || noSurname.length) { console.error(`no romanisation for: ${[...lost, ...noSurname].join(" ")}`); process.exit(1); }
  const out = fileURLToPath(new URL("../src/i18n/en/names.json", import.meta.url));
  const json = { _: "Generated by scripts/romanise.mjs (Wade–Giles, Taiwanese passport style); do not edit.", names: { surnames, chars } };
  await writeFile(out, JSON.stringify(json, null, 0).replace(/","/g, '",\n"') + "\n");
  console.log(`${out}: ${Object.keys(chars).length} characters, ${Object.keys(surnames).length} surnames`);
}
