// Generates src/core/name-data.js: Kangxi stroke counts, the 81-number table and the 三才 table for 姓名學.
//
//   node scripts/make-name-data.mjs <IRGSources.db> <shunshi-kangxi chars.json.gz> <shunshi-naming data dir>
//
// Inputs (read only, nothing from them is executed):
//   IRGSources.db       Unicode Unihan kRSUnicode and kIRG_TSource, as packaged in kanji-inspector 0.2.20 (MIT;
//                       Unihan data under the Unicode License). `npm pack kanji-inspector@0.2.20`, dist/db/.
//   chars.json.gz       shunshi-kangxi-core 0.1.1 (MIT), a second Kangxi stroke list used only for comparison.
//   shuli-81.json.gz, sancai-125.json.gz   shunshi-naming-core 0.1.0 (MIT): one of the two 81-number tables, and
//                       the only 三才 table available here.
//
// Kangxi strokes = strokes of the radical's full form (氵 counts as 水, 4) + the strokes outside the radical, both
// from Unihan's kRSUnicode. Characters come from Taiwan's CNS 11643 planes 1 and 2 (kIRG_TSource T1, T2): about
// 13,000 characters, covering names registered under 姓名條例.
import { DatabaseSync } from "node:sqlite";
import { readFileSync, writeFileSync } from "node:fs";
import { gunzipSync } from "node:zlib";
import { fileURLToPath } from "node:url";

const [dbPath, kxPath, namingDir] = process.argv.slice(2);
if (!namingDir) { console.error("usage: node scripts/make-name-data.mjs <IRGSources.db> <chars.json.gz> <naming data dir>"); process.exit(1); }
const gz = p => JSON.parse(gunzipSync(readFileSync(p)).toString());

// Strokes of the 214 Kangxi radicals, by radical number.
const RADICAL_STROKES = [];
for (const [from, to, n] of [[1, 6, 1], [7, 29, 2], [30, 60, 3], [61, 94, 4], [95, 117, 5], [118, 146, 6], [147, 166, 7], [167, 175, 8], [176, 186, 9], [187, 194, 10], [195, 200, 11], [201, 204, 12], [205, 208, 13], [209, 210, 14], [211, 211, 15], [212, 213, 16], [214, 214, 17]]) {
  for (let r = from; r <= to; r++) RADICAL_STROKES[r] = n;
}
const parse = v => { const [r, s] = v.split("."); return { radical: Number(r.replace(/['"]/g, "")), rest: Number(s) }; };

// 姓名學 counts the numerals one to ten by their value; the Kangxi count is kept as the other reading.
// 萬 is filed under 艸 in the Kangxi dictionary (15); 研 is 11 in its Kangxi form 硏.
const OVERRIDES = { 一: 1, 二: 2, 三: 3, 四: 4, 五: 5, 六: 6, 七: 7, 八: 8, 九: 9, 十: 10, 萬: 15 };
const EXTRA_READINGS = { 研: [11] };

const db = new DatabaseSync(dbPath, { readOnly: true });
const rows = db.prepare("select codepoint, kIRG_TSource as t, kRSUnicode as rs from IRGSources where kIRG_TSource is not null").all();
const kx = gz(kxPath).chars;

// Radicals whose element 字形五行 reads plainly; other radicals give no 字形 element.
const FORM = { 木: [75, 140, 118, 115], 火: [86], 土: [32, 46, 112, 102], 金: [167], 水: [85, 173, 15] };
const formOf = {};
for (const [el, rads] of Object.entries(FORM)) for (const r of rads) formOf[r] = el;

const byStrokes = {}, alternatives = {}, form = { 木: "", 火: "", 土: "", 金: "", 水: "" };
let count = 0, agree = 0, disputed = 0;
for (const { codepoint, t, rs } of rows) {
  if (!/^T[12]-/.test(t) || !rs) continue;
  const ch = String.fromCodePoint(codepoint);
  const readings = rs.split(/\s+/).map(parse);
  const derived = readings.map(r => RADICAL_STROKES[r.radical] + r.rest);
  let primary = OVERRIDES[ch] ?? derived[0];
  const alts = new Set(derived.filter(n => n !== primary));
  if (OVERRIDES[ch] !== undefined) alts.add(derived[0]);
  for (const n of EXTRA_READINGS[ch] || []) alts.add(n);
  const other = kx[ch];
  // A difference of three or more strokes means the other list looked up a different character (范 as 範).
  if (other && (other.src === "b" || other.src === "bi") && other.kx !== primary && Math.abs(other.kx - primary) <= 2) alts.add(other.kx);
  if (other && other.kx === derived[0]) agree++;
  alts.delete(primary);
  (byStrokes[primary] ||= []).push(ch);
  if (alts.size) { alternatives[ch] = [...alts].sort((a, b) => a - b); disputed++; }
  const el = formOf[readings[0].radical];
  if (el) form[el] += ch;
  count++;
}

const shuliB = gz(`${namingDir}/shuli-81.json.gz`);
const sancai = gz(`${namingDir}/sancai-125.json.gz`);
const LEVEL = { 大吉: 2, 吉: 1, 半吉: 0, 凶: -1, 大凶: -2 };
const EL = "木火土金水";
let sancaiCodes = "";
for (const a of EL) for (const b of EL) for (const c of EL) {
  const level = sancai[a + b + c] && LEVEL[sancai[a + b + c].level];
  if (level === undefined) throw new Error(`三才 ${a}${b}${c} missing`);
  sancaiCodes += String(level + 2);
}
const shuliCodes = Array.from({ length: 81 }, (_, i) => String(LEVEL[shuliB[String(i + 1)].level] + 2)).join("");

const out = `// Generated by scripts/make-name-data.mjs — do not edit by hand.
// Kangxi strokes from Unicode Unihan kRSUnicode (Unicode License, via kanji-inspector 0.2.20), CNS 11643 planes 1–2.
// ${count} characters; the second list (shunshi-kangxi-core 0.1.1) agrees on ${(agree / count * 100).toFixed(1)} %; ${disputed} characters have another reading.
// 81-number and 三才 tables: shunshi-naming-core 0.1.0 (MIT License, Copyright (c) 2026 Shunshi.AI).

// Characters by Kangxi stroke count.
export const BY_STROKES = ${JSON.stringify(Object.fromEntries(Object.entries(byStrokes).map(([n, cs]) => [n, cs.join("")])))};
// Other readings of disputed characters (another kRSUnicode radical, the other list, or a Kangxi form).
export const ALTERNATIVES = ${JSON.stringify(alternatives)};
// Characters whose radical gives a plain 字形五行.
export const FORM_ELEMENT = ${JSON.stringify(form)};
// 81 數理 from shunshi-naming-core, one digit per number 1–81: 4 大吉, 3 吉, 2 半吉, 1 凶, 0 大凶.
export const SHULI_SHUNSHI = "${shuliCodes}";
// 三才 天人地, one digit per combination in 木火土金水 order (天 slowest): 4 大吉 … 0 大凶.
export const SANCAI = "${sancaiCodes}";
`;
writeFileSync(fileURLToPath(new URL("../src/core/name-data.js", import.meta.url)), out);
console.log(`${count} characters, ${disputed} with other readings, agreement ${(agree / count * 100).toFixed(1)} %, ${(out.length / 1024).toFixed(0)} KB`);
