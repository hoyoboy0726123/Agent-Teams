function heatMap() {
  const color = v => (v >= 2 ? "var(--jade)" : v === 1 ? "#7fb39c" : v === 0 ? "#e6e1d6" : v === -1 ? "#d99a8f" : "var(--seal)");
  const word = v => (v >= 2 ? "旺" : v === 1 ? "順" : v === 0 ? "" : v === -1 ? "慎" : "守");
  return `<table class="heat"><thead><tr><th></th>${more.heat.map(h => `<th>${h.year}<small>${h.pillar}</small></th>`).join("")}</tr></thead><tbody>
    ${DOMAINS.map(([k, label]) => `<tr><th>${label}</th>${more.heat.map(h => `<td style="background:${color(h.levels[k])};color:${Math.abs(h.levels[k]) >= 2 ? "#fff" : "var(--ink-2)"}">${word(h.levels[k])}</td>`).join("")}</tr>`).join("")}
  </tbody></table>`;
}

