const pct = e => Math.round(d.analysis.scores[e] / total * 1000) / 10;

// ---------- charts ----------
function pillarTable() {
  const rows = Object.fromEntries(d.natal.table.rows.map(r => [r.label, r.cells]));
  const head = ["年柱", "月柱", "日柱", "時柱"];
  const tr = (label, cells, f = x => x) => `<tr><th>${label}</th>${cells.map(c => `<td>${f(c)}</td>`).join("")}</tr>`;
  return `<table class="pillars"><thead><tr><th></th>${head.map(h => `<th>${h}</th>`).join("")}</tr></thead><tbody>
    ${tr("十神", rows.主星, x => (x === "元女" ? "日主" : x))}
    ${tr("天干", rows.天干, c => `<b class="big">${el(c)}</b>`)}
    ${tr("地支", rows.地支, c => `<b class="big">${el(c)}</b>`)}
    ${tr("藏干", rows.藏干, c => c.map(x => `${el(x[0])}<small>${x[1]}</small>`).join(" "))}
    ${tr("副星", rows.副星, c => c.join("、"))}
    ${tr("納音", rows.納音)}
    ${tr("神煞", rows.神煞, c => `<span class="stars">${c.join("、")}</span>`)}
  </tbody></table>`;
}

function elementBars() {
  const order = ["火", "土", "金", "水", "木"];
  const role = { 水: "用神", 金: "喜神", 土: "喜神", 火: "忌神", 木: "仇神" };
  return `<div class="bars">${order.map(e => `<div class="bar"><span class="bl">${el(e)}<small>${role[e]}</small></span><span class="track"><i class="f-${e}" style="width:${Math.max(pct(e), 0.6)}%"></i></span><span class="bv">${pct(e)}%</span></div>`).join("")}</div>`;
}

function decadeLine() {
  const ds = d.luck.decades.slice(0, 8), W = 680, x0 = 8, w = (W - 16) / ds.length;
  const tone = { 吉: "var(--jade)", 平: "var(--ink-3)", 凶: "var(--seal)" };
  const tones = Object.fromEntries(d.decades.map(x => [x.name, x.tone]));
  const nowX = x0 + ((2026 - ds[0].startYear) / 10) * w;
  return `<svg class="timeline" viewBox="0 0 ${W} 92" role="img" aria-label="大運時間軸">
    ${ds.map((x, i) => `<g><rect x="${x0 + i * w + 2}" y="22" width="${w - 4}" height="30" rx="4" fill="${tone[tones[x.name]] || "var(--ink-3)"}" opacity="${x.name === "戊寅" ? 1 : 0.78}"/>
      <text x="${x0 + i * w + w / 2}" y="42" text-anchor="middle" class="tl-name">${x.name}</text>
      <text x="${x0 + i * w + w / 2}" y="68" text-anchor="middle" class="tl-sub">${x.startYear}–${String(x.endYear).slice(2)}</text>
      <text x="${x0 + i * w + w / 2}" y="84" text-anchor="middle" class="tl-sub">${x.startAge}–${x.endAge} 歲</text></g>`).join("")}
    <line x1="${nowX}" x2="${nowX}" y1="14" y2="56" stroke="var(--ink)" stroke-width="2"/>
    <text x="${nowX}" y="11" text-anchor="middle" class="tl-now">2026 你在這裡</text>
  </svg>`;
}

function tenYears() {
  const ys = d.years, W = 680, H = 236, mid = 100, k = 76, bw = 40, gap = (W - 40 - bw * ys.length) / (ys.length - 1);
  return `<svg class="years-chart" viewBox="0 0 ${W} ${H}" role="img" aria-label="2026 到 2035 年的流年起伏">
    <line x1="20" x2="${W - 20}" y1="${mid}" y2="${mid}" stroke="var(--rule)" />
    <text x="22" y="${mid - k + 4}" class="axis">順</text><text x="22" y="${mid + k}" class="axis">守</text>
    ${ys.map((y, i) => {
      const x = 20 + i * (bw + gap), v = y.favor.score, h = Math.max(3, Math.abs(v) * k);
      const top = v >= 0 ? mid - h : mid;
      return `<g><rect x="${x}" y="${top}" width="${bw}" height="${h}" rx="3" fill="${v >= 0.2 ? "var(--jade)" : v <= -0.2 ? "var(--seal)" : "var(--ink-3)"}"/>
        <text x="${x + bw / 2}" y="${H - 22}" text-anchor="middle" class="axis-y">${y.year}</text>
        <text x="${x + bw / 2}" y="${H - 6}" text-anchor="middle" class="axis-p">${y.pillar}</text></g>`;
    }).join("")}
  </svg>`;
}

